#!/usr/bin/env node
/**
 * Cache-busting stamper for the GitHub Pages deployment.
 *
 * This project is intentionally framework-free and bundler-free (see
 * docs/ARCHITECTURE.md) and the live site serves the repository's source files
 * directly from the branch root — there is no hashed-filename build step. That
 * means every asset URL (index.html's <link>/<script>, and every relative ES
 * module import reached from app.js) is a *stable* URL, so a returning visitor's
 * browser keeps serving the previously-cached app.js / styles.css / js/*.js even
 * after a new release is deployed. The symptom is a half-updated page: new
 * index.html markup, old behaviour and old styles.
 *
 * The fix, without introducing a bundler: derive a short build token from the
 * single existing version source (js/version.js's APP_VERSION) and stamp it as a
 * ?v=<token> query on every local asset URL. A changed token = new URLs = a
 * guaranteed fresh fetch, with no "clear your cache" instruction to anyone.
 *
 *   - index.html's own <link href="fonts.css"> / <link href="styles.css"> /
 *     <script src="app.js"> get ?v=<token> appended (re-stamped in place on each
 *     release).
 *   - The whole ES module graph is covered by a generated <script type=
 *     "importmap"> that maps every ./js/*.js and ./components/*.js specifier to
 *     the same path + ?v=<token>. The .js source files themselves are never
 *     touched — they keep their clean relative specifiers; only the import map
 *     (regenerated here between BUILD:CACHE-BUSTING markers) carries the token.
 *
 * index.html is the one URL that inherently cannot be self-versioned; it is left
 * to GitHub Pages' default `Cache-Control: max-age=600`, which reconciles within
 * ten minutes of a deploy and is revalidated by the CDN on each publish.
 *
 * Usage:
 *   node scripts/stamp-cache-busting.mjs           # rewrite index.html in place
 *   node scripts/stamp-cache-busting.mjs --check   # exit 1 if it is out of date
 *
 * `npm run build` runs this first; CI also runs it with --check so a release that
 * forgot to re-stamp is caught before it is deployed. Running it twice with the
 * same APP_VERSION produces no diff.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const indexPath = join(root, 'index.html');
const versionPath = join(root, 'js', 'version.js');

// index.html assets that live in the repo root and are referenced by a plain
// href/src (fonts.css is also inlined-by-data elsewhere, but the <link> here is a
// real network request that caches like any other).
const ROOT_ASSETS = ['fonts.css', 'styles.css', 'app.js'];

// Module directories whose every *.js file is reachable from app.js and must be
// covered by the import map. Flat — this project has no nested module folders.
const MODULE_DIRS = ['js', 'components'];

const MARKER_START = '<!-- BUILD:CACHE-BUSTING:START (generated by scripts/stamp-cache-busting.mjs — do not edit by hand) -->';
const MARKER_END = '<!-- BUILD:CACHE-BUSTING:END -->';

/**
 * @returns {Promise<string>} a URL-safe cache-busting token derived from
 * js/version.js's APP_VERSION — the build-metadata suffix (`2.1.0+20260907.1630`
 * → `20260907.1630`) when present, otherwise the sanitised version itself.
 */
export async function deriveToken() {
  const source = await readFile(versionPath, 'utf8');
  const match = /APP_VERSION\s*=\s*['"]([^'"]+)['"]/.exec(source);
  if (!match) throw new Error(`Could not find APP_VERSION in ${versionPath}`);
  const version = match[1];
  const raw = version.includes('+') ? version.slice(version.indexOf('+') + 1) : version;
  const token = raw.replace(/[^A-Za-z0-9._-]/g, '-');
  if (!token) throw new Error(`APP_VERSION "${version}" produced an empty cache-busting token.`);
  return token;
}

async function listModuleSpecifiers() {
  const specifiers = [];
  for (const dir of MODULE_DIRS) {
    const entries = await readdir(join(root, dir), { withFileTypes: true });
    for (const entry of entries) {
      if (entry.isFile() && entry.name.endsWith('.js')) specifiers.push(`./${dir}/${entry.name}`);
    }
  }
  return specifiers.sort();
}

function stampRootAssets(html, token) {
  let out = html;
  for (const asset of ROOT_ASSETS) {
    const escaped = asset.replace(/[.]/g, '\\.');
    // Matches href="asset" / src="asset" with or without an existing ?v=… ,
    // leaving any other query parameters (there are none today) untouched.
    const pattern = new RegExp(`((?:href|src)="${escaped})(?:\\?v=[^"]*)?(")`, 'g');
    out = out.replace(pattern, `$1?v=${token}$2`);
  }
  return out;
}

const escapeRe = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function buildImportMapBlock(specifiers, token, eol) {
  const imports = Object.fromEntries(specifiers.map(spec => [spec, `${spec}?v=${token}`]));
  const json = JSON.stringify({ imports }, null, 2)
    .split('\n')
    .map(line => (line ? `  ${line}` : line))
    .join(eol);
  return [
    `  ${MARKER_START}`,
    '  <script type="importmap">',
    json,
    '  </script>',
    `  ${MARKER_END}`
  ].join(eol);
}

function injectImportMap(html, block, eol) {
  const existing = new RegExp(`[ \\t]*${escapeRe(MARKER_START)}[\\s\\S]*?${escapeRe(MARKER_END)}`);
  if (existing.test(html)) return html.replace(existing, block);
  // First run: place it at the end of <head>, which still puts it ahead of the
  // <body> module script (an import map must precede the first module load).
  const anchor = /([ \t]*<\/head>)/;
  if (!anchor.test(html)) throw new Error('Could not find the </head> anchor to insert the import map before.');
  return html.replace(anchor, `${block}${eol}$1`);
}

export async function computeStampedIndex() {
  const [token, specifiers, original] = await Promise.all([
    deriveToken(),
    listModuleSpecifiers(),
    readFile(indexPath, 'utf8')
  ]);
  const eol = original.includes('\r\n') ? '\r\n' : '\n';
  const stamped = injectImportMap(
    stampRootAssets(original, token),
    buildImportMapBlock(specifiers, token, eol),
    eol
  );
  return { token, original, stamped };
}

async function main() {
  const check = process.argv.includes('--check');
  const { token, original, stamped } = await computeStampedIndex();

  if (original === stamped) {
    console.log(`index.html cache-busting is up to date (token ${token}).`);
    return;
  }

  if (check) {
    console.error(
      `index.html is not stamped for the current APP_VERSION (token ${token}).\n` +
        'Run "npm run stamp" (or "npm run build") and commit the result.'
    );
    process.exitCode = 1;
    return;
  }

  await writeFile(indexPath, stamped);
  console.log(`Stamped index.html asset URLs and import map with ?v=${token}.`);
}

// Only run when invoked directly (node scripts/stamp-cache-busting.mjs); when
// imported by build.mjs, only the exported helpers are used.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
